def P(rel):
    return os.path.join(ROOT, *rel.split("/"))


def backup(rel):
    if os.path.exists(P(rel)):
        dst = os.path.join(BK, *rel.split("/"))
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        if not os.path.exists(dst):
            shutil.copy2(P(rel), dst)


def write(rel, text):
    os.makedirs(os.path.dirname(P(rel)), exist_ok=True)
    open(P(rel), "w", encoding="utf-8", newline="\n").write(text)


for rel, text in FILES.items():
    if os.path.exists(P(rel)):
        if open(P(rel), encoding="utf-8").read() == text:
            skipped.append(rel + " (already installed)"); continue
        backup(rel)
    write(rel, text); done.append(rel)


def patch(rel, marker, edits, label):
    """edits: list of (old, new). All must match exactly once, or nothing changes."""
    if not os.path.exists(P(rel)):
        problems.append(f"{rel} not found"); return
    s = open(P(rel), encoding="utf-8").read()
    if marker in s:
        skipped.append(f"{rel} (already patched)"); return
    if not all(s.count(o) == 1 for o, _ in edits):
        problems.append(f"{rel} differs from what was expected: NOT changed ({label}). The agent applies it by hand."); return
    backup(rel)
    for o, n in edits:
        s = s.replace(o, n)
    write(rel, s); done.append(f"{rel} ({label})")


