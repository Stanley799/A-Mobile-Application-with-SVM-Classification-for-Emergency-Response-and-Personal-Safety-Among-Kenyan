def main():
    data = base64.b64decode("".join(B64.split()))
    if hashlib.sha256(data).hexdigest() != EXPECT_SHA256:
        print("FAIL: embedded content is corrupted (hash mismatch). Re-download the installer."); sys.exit(1)
    doc = json.loads(data.decode("utf-8"))
    root = PROJECT if os.path.isdir(PROJECT) else os.getcwd()
    if not os.path.isdir(os.path.join(root, "mobile")):
        print("FAIL: cannot find the 'mobile' folder under", root); sys.exit(1)
    dest = os.path.join(root, REL)
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    if os.path.exists(dest):
        if open(dest, "rb").read() == data:
            print("OK: already installed and identical:", dest); return
        n = 1
        while os.path.exists(dest + ".bak-%d" % n): n += 1
        shutil.copy2(dest, dest + ".bak-%d" % n)
        print("Backed up existing file to", dest + ".bak-%d" % n)
    with open(dest, "wb") as f: f.write(data)
    drafted = sum(1 for g in doc["guides"] if g["status"] == "draft")
    stubs = sum(1 for g in doc["guides"] if g["status"] == "needs_content")
